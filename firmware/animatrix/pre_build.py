Import("env")
import os
import subprocess
import hashlib

# -----------------------------------------------------------------------------
# 1. Dynamic Git Versioning
# -----------------------------------------------------------------------------
try:
    git_rev = subprocess.check_output(
        ["git", "describe", "--tags", "--always", "--dirty"],
        cwd=env.subst("$PROJECT_DIR")
    ).decode("utf-8").strip()
    if not git_rev.startswith("v"):
        git_rev = f"v1.3.0-{git_rev}"
except Exception as e:
    git_rev = "v1.3.0-unknown"

print(f"\n[Animatrix Build] Dynamic Firmware Version: {git_rev}")
env.Append(CPPDEFINES=[("FIRMWARE_VERSION", f'\\"{git_rev}\\"')])

# -----------------------------------------------------------------------------
# 2. Embed Data Files into C Header for LittleFS Self-Provisioning
# -----------------------------------------------------------------------------
data_dir = os.path.join(env.subst("$PROJECT_DIR"), "data")
header_path = os.path.join(env.subst("$PROJECT_DIR"), "include", "embedded_files.h")

def generate_embedded_header():
    if not os.path.isdir(data_dir):
        print(f"[Animatrix Build] Warning: data directory not found at {data_dir}")
        return

    files = []
    hasher = hashlib.md5()

    for root, _, filenames in os.walk(data_dir):
        for fname in sorted(filenames):
            full_path = os.path.join(root, fname)
            rel_path = "/" + os.path.relpath(full_path, data_dir).replace("\\", "/")
            files.append((rel_path, full_path))

    lines = [
        "// Auto-generated by pre_build.py - DO NOT EDIT MANUALLY",
        "#ifndef EMBEDDED_FILES_H",
        "#define EMBEDDED_FILES_H",
        "",
        "#include <Arduino.h>",
        "",
        "struct EmbeddedFile {",
        "    const char* path;",
        "    const uint8_t* data;",
        "    size_t size;",
        "};",
        ""
    ]

    for idx, (rel_path, full_path) in enumerate(files):
        with open(full_path, "rb") as f:
            data = f.read()
        hasher.update(rel_path.encode("utf-8"))
        hasher.update(data)
        var_name = f"EMBEDDED_FILE_{idx}"
        hex_bytes = ", ".join(f"0x{b:02x}" for b in data)
        lines.append(f"// {rel_path} ({len(data)} bytes)")
        lines.append(f"static const uint8_t {var_name}[] PROGMEM = {{ {hex_bytes} }};")
        lines.append("")

    fs_hash = hasher.hexdigest()[:12]
    lines.append(f'#define EMBEDDED_FS_HASH "{fs_hash}"')
    lines.append("")

    lines.append("static const EmbeddedFile EMBEDDED_FILES[] = {")
    for idx, (rel_path, _) in enumerate(files):
        var_name = f"EMBEDDED_FILE_{idx}"
        lines.append(f'    {{ "{rel_path}", {var_name}, sizeof({var_name}) }},')
    lines.append("};")
    lines.append("")
    lines.append(f"static const size_t NUM_EMBEDDED_FILES = {len(files)};")
    lines.append("")
    lines.append("#endif // EMBEDDED_FILES_H\n")

    content = "\n".join(lines)

    # Only write if changed to avoid unnecessary recompilation
    if os.path.exists(header_path):
        with open(header_path, "r", encoding="utf-8") as f:
            if f.read() == content:
                print(f"[Animatrix Build] embedded_files.h is up to date (payload hash: {fs_hash}).")
                return

    with open(header_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[Animatrix Build] Generated embedded_files.h ({len(files)} files embedded, payload hash: {fs_hash})")

generate_embedded_header()
